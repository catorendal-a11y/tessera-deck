"""Reproduce the pinned offline Lucide catalog and the P4 glyph source font."""
import base64
import hashlib
import json
from pathlib import Path
import re
import tarfile
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
VERSION = '1.59.0'
INTEGRITY = 'MuHZYaXbHgzN2QO6D3OM19bj09A+8GJiFSdXIMlbnLLEGQQ9+NRH2KaCxuivevD3Y23vM74kV17XBifgtqhfEg=='


def main():
    archive = ROOT / 'build/icon-pack' / f'lucide-static-{VERSION}.tgz'
    archive.parent.mkdir(parents=True, exist_ok=True)
    if not archive.exists():
        urllib.request.urlretrieve(f'https://registry.npmjs.org/lucide-static/-/lucide-static-{VERSION}.tgz', archive)
    actual = base64.b64encode(hashlib.sha512(archive.read_bytes()).digest()).decode()
    if actual != INTEGRITY:
        raise ValueError('Lucide package integrity mismatch')
    destination = ROOT / 'vendor/lucide'
    destination.mkdir(parents=True, exist_ok=True)
    with tarfile.open(archive) as package:
        def read(name):
            return package.extractfile('package/' + name).read()
        points = json.loads(read('font/codepoints.json'))
        tags = json.loads(read('tags.json'))
        svg_names = {Path(item.name).stem for item in package.getmembers()
                     if re.fullmatch(r'package/icons/[a-z0-9-]+\.svg', item.name)}
        grouped = {}
        for name, code in points.items():
            grouped.setdefault(code, []).append(name)
        entries = []
        for code, aliases in sorted(grouped.items()):
            names = [name for name in aliases if name in svg_names]
            if not names:
                continue  # Retired glyphs have no current SVG preview.
            # Favor an actively tagged icon name over a deprecated alias.
            names.sort(key=lambda name: (name not in tags, name))
            name = names[0]
            svg = read(f'icons/{name}.svg').decode()
            if '<script' in svg or 'href=' in svg or '<foreignObject' in svg:
                raise ValueError('Unexpected executable/external SVG content')
            entries.append(dict(id=f'lc:{code:x}', name=name, aliases=sorted(aliases),
                                tags=sorted({tag for alias in aliases for tag in tags.get(alias, [])}), svg=svg))
        for name, data in [('LICENSE', read('LICENSE')), ('lucide.ttf', read('font/lucide.ttf')),
                           ('codepoints.json', read('font/codepoints.json'))]:
            (destination / name).write_bytes(data)
        manifest = dict(name='Lucide', version=VERSION, license='ISC', count=len(entries),
                        source='https://github.com/lucide-icons/lucide', icons=entries)
        (destination / 'catalog.json').write_text(json.dumps(manifest, separators=(',', ':'), ensure_ascii=False), encoding='utf-8')
        first, last = min(grouped), max(grouped)
        mask = bytearray((last-first+8)//8)
        for item in entries:
            offset = int(item['id'][3:], 16)-first
            mask[offset//8] |= 1 << (offset%8)
        (ROOT / 'main/ui/icon_pack_map.h').write_text(
            '// Generated by tools/vendor_icon_pack.py; Lucide '+VERSION+' (ISC).\n#pragma once\n'
            f'#define DECK_LUCIDE_FIRST 0x{first:x}\n#define DECK_LUCIDE_LAST 0x{last:x}\n#define DECK_LUCIDE_COUNT {len(entries)}\n'
            'static const unsigned char deck_lucide_mask[] = {'+','.join(f'0x{value:02x}' for value in mask)+'};\n', encoding='utf-8')
        (destination / 'README.md').write_text(
            f'# Lucide {VERSION}\n\n{len(entries)} unique icons, offline SVG catalog and source font.\n\n'
            'Source: https://github.com/lucide-icons/lucide\n\n'
            'ISC license included unchanged. Original notices remain in SVGs.\n\n'
            f'Pinned npm package: lucide-static@{VERSION}\n\nSHA512: {INTEGRITY}\n\n'
            'Rebuild: `python tools/vendor_icon_pack.py`, then `tools/build_icon_font.cmd`.\n'
            'Icon IDs are pinned to this font version; do not remap existing IDs when updating.\n', encoding='utf-8')
    print(f'Vendored {len(entries)} unique Lucide icons; {sum(len(e["aliases"]) for e in entries)} searchable names.')


if __name__ == '__main__':
    main()
